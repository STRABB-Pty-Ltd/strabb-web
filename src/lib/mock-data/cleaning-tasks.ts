import type { CleaningTask } from "@/types/cleaning-task";
import { REFERENCE_NOW } from "./reference-date";

const hours = (offset: number) => {
  const d = new Date(REFERENCE_NOW);
  d.setUTCHours(d.getUTCHours() + offset);
  return d.toISOString();
};

